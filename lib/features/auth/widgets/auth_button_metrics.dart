/// 로그인 화면의 세 버튼이 함께 쓰는 값.
///
/// 카카오·Apple·이메일 버튼은 한 덩어리로 세로로 놓인다. 값을 각자 들고
/// 있으면 한 곳만 바뀌어 가운데 버튼만 각지는 일이 생긴다. Apple 버튼은
/// 패키지가 만들어 주는 것이라 기본값(높이 44 · 모서리 8)이 따로 있어서 더
/// 그렇다. 셋이 같은 값을 보게 한곳에 둔다.
library;

/// 버튼 높이. 카카오·이메일이 쓴다.
///
/// Apple 버튼에는 넘기지 않는다 — 그 위젯은 글자 크기를 높이에서 뽑아
/// 쓰므로(height x 0.43) 여기 값을 주면 글자만 22pt 로 커져 오히려 더
/// 어긋난다. 그래서 모서리만 맞추고 높이는 그쪽 기본값(44)을 둔다.
const double kAuthButtonHeight = 52;

/// 모서리 반지름. 세 버튼이 모두 쓴다. 각 높이의 절반을 넘겨 알약이 된다.
const double kAuthButtonRadius = 50;
